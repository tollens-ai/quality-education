// A glyph is [advance, polyline, polyline, ...]. A polyline is a list of points; a point is
// [x, y], or ['q', x0,y0, cx,cy, x1,y1, ...] for a corner the pen rounds off with a real curve.
// Nothing in this film is an arc.
function toRuns(polys) {
  const runs = [];
  for (const poly of polys) {
    let cur = [];
    for (const p of poly) {
      if (Array.isArray(p) && p[0] === 'q') {
        let sx = p[1], sy = p[2];
        for (let i = 1; i + 5 < p.length + 1 && i + 5 <= p.length; i += 2) {
          const cx = p[i + 2], cy = p[i + 3], x1 = p[i + 4], y1 = p[i + 5];
          if (x1 === undefined) break;
          for (let k = 1; k <= 6; k++) {
            const t = k / 6, mt = 1 - t;
            cur.push([mt * mt * sx + 2 * mt * t * cx + t * t * x1, mt * mt * sy + 2 * mt * t * cy + t * t * y1]);
          }
          sx = x1; sy = y1;
        }
        continue;
      }
      cur.push(p);
    }
    if (cur.length > 1) runs.push({ pts: cur });
  }
  return runs;
}

export function glyph(ch) {
  return G[ch] || G['?'];
}

export function has(ch) { return !!G[ch]; }

export function advance(ch) { return glyph(ch)[0]; }

// The nib is fat (about 0.115em), so every glyph is drawn half a nib in from its origin and
// advances by its width plus a nib and a gap. Without this the letters touch at display size.
const BEAR = 0.058;
const TRACK = 0.075;

export function measure(text, size, tracking = TRACK) {
  let w = 0;
  for (const ch of text) w += glyph(ch)[0] + tracking + 2 * BEAR;
  return Math.max(0, w - tracking - 2 * BEAR) * size;
}

// Lay a string out on one line, y is the baseline. Returns each glyph's strokes in pixels.
export function layout(text, x, y, size, o = {}) {
  const tracking = o.tracking ?? TRACK;
  const bear = o.bear ?? BEAR;
  const boil = o.boil ?? 0;
  const slant = o.slant ?? 0;
  const out = [];
  let cx = x;
  if (o.align === 'center') cx = x - measure(text, size, tracking) / 2;
  else if (o.align === 'right') cx = x - measure(text, size, tracking);
  for (const ch of text) {
    const gl = glyph(ch);
    for (const run of toRuns(gl.slice(1))) {
      const pts = run.pts.map(([gx, gy]) => [cx + (bear + gx + slant * (1 - gy)) * size, y - (1 - gy) * size]);
      out.push({ pts, boil, colour: o.colour });
    }
    cx += (gl[0] + tracking + 2 * bear) * size;
  }
  return out;
}

// Set a line of type with the film's own pen, so the letters overshoot and miss like everything
// else in the film. `size` is the cap height in pixels; `w` is the nib's weight.
export function drawText(g, text, x, y, size, o = {}) {
  const strokes = layout(text, x, y, size, o);
  const key = o.id || text;
  strokes.forEach((s, i) => line(g, `${key}#${i}`, s.pts, {
    w: o.w ?? size * 0.115, colour: o.colour, boil: o.boil, rough: 0.55, over: 1.1, taper: 0.3,
  }));
  return measure(text, size, o.tracking ?? TRACK);
}

// One word, so a scene can let a word arrive with the voice instead of setting a whole line.
export function drawWord(g, text, x, y, size, o = {}) {
  return drawText(g, text, x, y, size, { ...o, id: o.id || `w:${text}` });
}
